def remove_samples_by_id(
    input_path: Path,
    output_path: Path,
    remove_ids: list,
) -> None:
    """
    删除 JSONL 中 sample_idx 位于 remove_ids 中的样本。
    """

    # 统一转换为字符串，兼容 sample_id 为整数或字符串的情况
    remove_id_set = {str(sample_idx) for sample_idx in remove_ids}

    total_count = 0
    removed_count = 0
    kept_count = 0

    with input_path.open("r", encoding="utf-8") as fin, \
            output_path.open("w", encoding="utf-8") as fout:

        for line_number, line in enumerate(fin, start=1):
            line = line.strip()

            # 跳过空行
            if not line:
                continue

            try:
                sample = json.loads(line)
            except json.JSONDecodeError as error:
                print(f"警告：第 {line_number} 行 JSON 格式错误，已跳过：{error}")
                continue

            total_count += 1
            sample_idx = sample.get("sample_idx")

            if str(sample_idx) in remove_id_set:
                removed_count += 1
                continue

            fout.write(json.dumps(sample, ensure_ascii=False) + "\n")
            kept_count += 1

    print("处理完成")
    print(f"原始样本数量：{total_count}")
    print(f"删除样本数量：{removed_count}")
    print(f"保留样本数量：{kept_count}")
    print(f"输出文件路径：{output_path.resolve()}")


